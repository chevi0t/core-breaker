def main():
    args = sys.argv[1:]
    maps = ROOT / "prototype" / "maps.js"
    if "--maps" in args:
        i = args.index("--maps")
        maps = pathlib.Path(args[i + 1])
        del args[i:i + 2]
    version = args[0] if args else "dev"
    if "window.MAP_DATA" not in maps.read_text(encoding="utf-8"):
        sys.exit(f"{maps} はマップのデータではありません")
    html = SRC.read_text(encoding="utf-8")
    if CDN_TAG not in html:
        sys.exit("three.js の読み込みタグが見つかりません: " + CDN_TAG)
    html = HEAD + html.replace(CDN_TAG, '<script src="three.min.js"></script>') + "\n</html>\n"

    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    out = dist / f"core-breaker-v{version}.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("core-breaker/index.html", html)
        z.write(VENDOR / "three.min.js", "core-breaker/three.min.js")
        z.write(ROOT / "prototype" / "sounds.js", "core-breaker/sounds.js")
        z.write(ROOT / "prototype" / "music.js", "core-breaker/music.js")
        z.write(maps, "core-breaker/maps.js")
        z.write(ROOT / "prototype" / "maps" / "README.md", "core-breaker/MAPS.md")
        z.write(ROOT / "sounds" / "CREDITS.md", "core-breaker/SOUND-CREDITS.md")
        z.write(VENDOR / "LICENSE", "core-breaker/LICENSE-three.js.txt")
        z.writestr("core-breaker/README.txt", README.format(version=version))
        for name in ("DESIGN.md", "AGENTS.md", "CLAUDE.md"):
            z.write(DOCS / name, "core-breaker/" + name)
    print(out, out.stat().st_size, "bytes ／ マップ:", maps)


if __name__ == "__main__":
    main()
